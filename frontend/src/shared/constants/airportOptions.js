export function findAirportOption(code) {
  const normalizedCode = String(code ?? '').trim().toUpperCase()
  return AIRPORT_OPTIONS.find(option => option.code === normalizedCode) ?? null
}

export function buildAirportOptionLabel(code, locale = 'zh-CN', fallbackName = '') {
  const normalizedCode = String(code ?? '').trim().toUpperCase()
  const airport = findAirportOption(normalizedCode)
  if (!airport) {
    const fallback = String(fallbackName ?? '').trim()
    if (fallback && normalizedCode) {
      return `${fallback} ${normalizedCode}`
    }
    return normalizedCode || fallback || '-'
  }

  return locale === 'zh-CN'
    ? `${airport.airportNameZh} ${airport.code}`
    : `${airport.airportNameEn} ${airport.code}`
}
